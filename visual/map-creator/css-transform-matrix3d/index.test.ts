import { getMatrix3d } from "."

const source = [
  [0, 0],
  [100, 0],
  [100, 100],
  [0, 100],
]

test('simple almost perfect vertical rectangle', () => {
  const target = [[384,431],[387,241],[429,241],[426,431]]
  expect(getMatrix3d(source, target)).toEqual("matrix3d(0.02999999999999999889,-1.89999999999999991118,0.00000000000000000000,0.00000000000000000000,0.41999999999999998446,0.00000000000000000000,0.00000000000000000000,0.00000000000000000000,0.00000000000000000000,0.00000000000000000000,1.00000000000000000000,0.00000000000000000000,384.00000000000000000000,431.00000000000000000000,0.00000000000000000000,1.00000000000000000000)")
})

test('simple almost perfect horizontal rectangle', () => {
  const target = [[624,170],[624,212],[458,212],[458,170]]
  expect(getMatrix3d(source, target)).toEqual("matrix3d(0.00000000000000000000,0.41999999999999998446,0.00000000000000000000,0.00000000000000000000,-1.65999999999999992006,0.00000000000000000000,0.00000000000000000000,0.00000000000000000000,0.00000000000000000000,0.00000000000000000000,1.00000000000000000000,0.00000000000000000000,624.00000000000000000000,170.00000000000000000000,0.00000000000000000000,1.00000000000000000000)")
})

